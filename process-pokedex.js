// Función para obtener el nombre base de un Pokémon
function getBaseName(name) {
    return name
        .replace(/^(mega|gigantamax)\s+/i, '')
        .replace(/-(x|y)$/i, '')
        .replace(/-(mega|gigantamax)$/i, '')
        .replace(/-(alolan|galarian|hisuian|paldean)$/i, '')
        .replace(/-(male|female)$/i, '')
        .replace(/-ice$/i, '')
        .replace(/-noice$/i, '')
        .replace(/-shadow$/i, '')
        .replace(/-plant$/i, '')
        .replace(/-sand$/i, '')
        .replace(/-trash$/i, '')
        .replace(/-wash$/i, '')
        .replace(/-fan$/i, '')
        .replace(/-frost$/i, '')
        .replace(/-heat$/i, '')
        .replace(/-mow$/i, '')
        .replace(/-electric$/i, '')
        .trim();
}

